"""One declared rod design generates the portable URDF and the planar MJCF."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent


def numbers(values):
    return ' '.join(f'{float(x):.16g}' for x in values)


def rod(spec, section):
    a, b = section
    c, mass = spec['length_m'], spec['mass_kg']
    return [a, b, c], [0, 0, spec['direction']*c/2], [
        mass*(b*b+c*c)/12, mass*(a*a+c*c)/12, mass*(a*a+b*b)/12]


def write_xml(root, path, note):
    ET.indent(root, space='  ')
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- '+note+' -->\n'+ET.tostring(root, encoding='unicode')+'\n')


def build():
    cfg = json.loads((HERE/'design.json').read_text())
    folder = HERE/'models'; folder.mkdir(exist_ok=True)
    limits, drive = cfg['joint'], cfg['drive']
    for name, sign in [('left_hip', 1), ('right_hip', -1)]:
        unit = next(u for u in cfg['units'] if u['joint'] == name)
        assert unit['xyz'] == [0, sign*cfg['hip_half_spacing_m'], 0]
    robot = ET.Element('robot', name='unit_bfm_biped_v2_rods_v1_1')
    materials = {'torso': '.4 .46 .53 1', 'left_leg': '.16 .48 .82 1',
                 'right_leg': '.88 .43 .17 1', 'joint_marker': '.23 .27 .32 1'}
    for name, rgba in materials.items():
        ET.SubElement(ET.SubElement(robot, 'material', name=name), 'color', rgba=rgba)
    for name, spec in cfg['links'].items():
        size, pos, inertia = rod(spec, cfg['rod_section_m'])
        link = ET.SubElement(robot, 'link', name=name)
        inertial = ET.SubElement(link, 'inertial')
        ET.SubElement(inertial, 'origin', xyz=numbers(pos))
        ET.SubElement(inertial, 'mass', value=str(spec['mass_kg']))
        ET.SubElement(inertial, 'inertia', ixx=str(inertia[0]), iyy=str(inertia[1]), izz=str(inertia[2]), ixy='0', ixz='0', iyz='0')
        material = 'torso' if name == 'pelvis' else ('left_leg' if name.startswith('left') else 'right_leg')
        for kind in ('visual', 'collision'):
            element = ET.SubElement(link, kind, name=name+'_'+kind)
            ET.SubElement(element, 'origin', xyz=numbers(pos))
            ET.SubElement(ET.SubElement(element, 'geometry'), 'box', size=numbers(size))
            if kind == 'visual': ET.SubElement(element, 'material', name=material)
        if name != 'pelvis':
            visual = ET.SubElement(link, 'visual', name=name+'_joint_marker')
            ET.SubElement(visual, 'origin', xyz='0 0 0', rpy='1.5707963267948966 0 0')
            ET.SubElement(ET.SubElement(visual, 'geometry'), 'cylinder', radius='.023', length='.05')
            ET.SubElement(visual, 'material', name='joint_marker')
        else:
            # Ideal axial mounting connector: visualization only, not an
            # additional physical crossbar with unmodelled mass or inertia.
            visual = ET.SubElement(link, 'visual', name='hip_axis_mount_marker')
            ET.SubElement(visual, 'origin', xyz='0 0 0', rpy='1.5707963267948966 0 0')
            ET.SubElement(ET.SubElement(visual, 'geometry'), 'cylinder',
                          radius='.008', length=str(2*cfg['hip_half_spacing_m']))
            ET.SubElement(visual, 'material', name='joint_marker')
    for u in cfg['units']:
        j = ET.SubElement(robot, 'joint', name=u['joint'], type='revolute')
        ET.SubElement(j, 'parent', link=u['P']); ET.SubElement(j, 'child', link=u['D'])
        ET.SubElement(j, 'origin', xyz=numbers(u['xyz']), rpy='0 0 0')
        ET.SubElement(j, 'axis', xyz=numbers(limits['axis']))
        ET.SubElement(j, 'limit', lower=str(limits['lower_rad']), upper=str(limits['upper_rad']),
                      effort=str(drive['nominal_request_Nm']), velocity=str(limits['urdf_velocity_metadata_rad_s']))
        ET.SubElement(j, 'dynamics', damping=str(limits['damping']), friction=str(limits['frictionloss']))
    write_xml(robot, folder/'biped_4dof.urdf',
              'Generated by build_model.py from design.json. Five uniform rods; four independent pitch drives. '+
              'Cylinders are massless visual joint markers. URDF root is not welded to world. '+
              'The companion MJCF/runtime implement the planar root and V2 drive dynamics.')

    model = ET.Element('mujoco', model=robot.get('name'))
    ET.SubElement(model, 'compiler', angle='radian', autolimits='true', inertiafromgeom='false')
    ET.SubElement(model, 'option', timestep=str(drive['physics_dt_s']), integrator='implicitfast',
                  solver='Newton', iterations='20', gravity='0 0 -9.81')
    default = ET.SubElement(model, 'default')
    ET.SubElement(default, 'joint', type='hinge', axis=numbers(limits['axis']),
                  range=numbers([limits['lower_rad'], limits['upper_rad']]),
                  damping=str(limits['damping']), frictionloss=str(limits['frictionloss']),
                  armature=str(limits['armature']), margin=str(limits['margin_rad']),
                  solreflimit=numbers(limits['solreflimit']), solimplimit=numbers(limits['solimplimit']))
    ET.SubElement(default, 'geom', friction='.8 .005 .0001', condim='3', solref='.01 1')
    world = ET.SubElement(model, 'worldbody')
    ET.SubElement(world, 'light', pos='1 -2 3')
    ET.SubElement(world, 'geom', name='floor', type='plane', size='5 5 .1', rgba='.4 .42 .44 1')
    pelvis = ET.SubElement(world, 'body', name='pelvis', pos='0 0 .601')
    for name, kind, axis in [('root_x', 'slide', '1 0 0'), ('root_z', 'slide', '0 0 1'), ('root_pitch', 'hinge', '0 1 0')]:
        ET.SubElement(pelvis, 'joint', name=name, type=kind, axis=axis,
                      limited='false', damping='0', frictionloss='0', armature='0')
    bodies = {'pelvis': pelvis}
    for u in cfg['units']:
        child = ET.SubElement(bodies[u['P']], 'body', name=u['D'], pos=numbers(u['xyz']))
        ET.SubElement(child, 'joint', name=u['joint'])
        bodies[u['D']] = child
    for name, spec in cfg['links'].items():
        size, pos, inertia = rod(spec, cfg['rod_section_m'])
        body = bodies[name]
        ET.SubElement(body, 'inertial', pos=numbers(pos), mass=str(spec['mass_kg']), diaginertia=numbers(inertia))
        material = 'torso' if name == 'pelvis' else ('left_leg' if name.startswith('left') else 'right_leg')
        ET.SubElement(body, 'geom', name=name+'_box', type='box', size=numbers([v/2 for v in size]),
                      pos=numbers(pos), rgba=materials[material])
        if name == 'pelvis':
            ET.SubElement(body, 'geom', name='hip_axis_mount_marker', type='cylinder',
                          size=numbers([.008, cfg['hip_half_spacing_m']]),
                          euler='1.5707963267948966 0 0', contype='0', conaffinity='0', mass='0',
                          rgba=materials['joint_marker'])
    contact = ET.SubElement(model, 'contact')
    actuators = ET.SubElement(model, 'actuator')
    for u in cfg['units']:
        ET.SubElement(contact, 'exclude', body1=u['P'], body2=u['D'])
        ET.SubElement(actuators, 'motor', name=u['joint']+'_drive', joint=u['joint'], gear='1',
                      ctrllimited='true', ctrlrange=numbers([-drive['capacity_Nm'], drive['capacity_Nm']]))
    write_xml(model, folder/'biped_4dof.xml',
              'Generated companion scene. Root has unactuated x/z/pitch only. '+
              'Drive inputs are filtered actual torques supplied by runtime.py, not raw policy commands.')
    return cfg


if __name__ == '__main__':
    build()
    print('Wrote portable URDF and planar MuJoCo scene.')
